import assert from 'node:assert/strict'
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, symlinkSync, unlinkSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { inspectFacts, validateFacts } from './inspect-facts.mjs'

const root = mkdtempSync(join(tmpdir(), 'dss-scoped-facts-'))
const inspect = request => inspectFacts(root, request, Date.now() + 5000)
try {
  mkdirSync(join(root, 'feature')); mkdirSync(join(root, 'unrelated'))
  writeFileSync(join(root, 'feature/app.cjs'), 'exports.day = require("./utils.cjs").parseDate\n')
  writeFileSync(join(root, 'feature/utils.cjs'), 'exports.parseDate = s => Number(s.slice(-2))\n')
  for (let n = 0; n < 201; n++) writeFileSync(join(root, 'unrelated', `${n}.txt`), 'unrelated\n')
  assert.equal(inspect({ paths: [], terms: ['parseDate'] }).incomplete, true, 'legacy whole-project search must still reject incomplete ranges')
  const request = { paths: [], terms: ['parseDate'], searchPaths: ['feature'] }
  const scoped = inspect(request)
  assert.equal(scoped.incomplete, false, 'a complete local scope must survive unrelated repository size')
  assert.deepEqual(scoped.facts.map(f => f.path), ['feature/app.cjs', 'feature/utils.cjs'])
  assert.deepEqual(scoped.searchScope, { paths: ['feature'], terms: ['parseDate'] })
  assert.equal(validateFacts(root, scoped, Date.now() + 5000), true)
  writeFileSync(join(root, 'feature/new.cjs'), 'exports.day = require("./utils.cjs").parseDate\n')
  assert.equal(validateFacts(root, scoped, Date.now() + 5000), false, 'adding a caller inside the scope invalidates its complete range')
  unlinkSync(join(root, 'feature/new.cjs'))
  mkdirSync(join(root, 'feature/empty'))
  const withEmpty = inspect(request)
  assert.equal(withEmpty.incomplete, false)
  writeFileSync(join(root, 'feature/empty/new.cjs'), 'exports.day = require("../utils.cjs").parseDate\n')
  assert.equal(validateFacts(root, withEmpty, Date.now() + 5000), false, 'formerly empty directories remain part of the source range')
  unlinkSync(join(root, 'feature/empty/new.cjs'))
  assert.equal(validateFacts(root, { ...scoped, searchScope: { paths: ['unrelated'], terms: ['parseDate'] } }, Date.now() + 5000), false, 'scope metadata must be bound to its manifest')
  writeFileSync(join(root, 'feature/large.cjs'), '/* unrelated documentation */\n'.repeat(1500) + 'exports.day = require("./utils.cjs").parseDate\n')
  const focused = inspect({ paths: [], terms: ['parseDate'], searchPaths: ['feature/large.cjs'] })
  assert.equal(focused.incomplete, false)
  assert.equal(focused.facts.length, 1)
  assert.equal(focused.facts[0].startLine, 1501)
  const overlap = inspect({ paths: [], terms: ['parseDate'], searchPaths: ['feature', 'feature/app.cjs', 'feature'] })
  assert.equal(overlap.incomplete, false)
  assert.equal(new Set(overlap.files.map(f => f.path)).size, overlap.files.length)
  for (const searchPaths of [['../outside'], ['/etc'], ['.env'], ['missing'], ['feature/../unrelated'], ['unrelated'], []]) assert.equal(inspect({ paths: [], terms: ['parseDate'], searchPaths }).incomplete, true, JSON.stringify(searchPaths))
  symlinkSync(join(root, 'feature'), join(root, 'alias'))
  assert.equal(inspect({ paths: [], terms: ['parseDate'], searchPaths: ['alias'] }).incomplete, true)
  unlinkSync(join(root, 'alias'))
  writeFileSync(join(root, 'feature/private.cjs'), 'const password = "secret-value-123"; parseDate()\n')
  const secret = inspect({ paths: [], terms: ['parseDate'], searchPaths: ['feature/private.cjs'] })
  assert.equal(secret.incomplete, true)
  assert.ok(!JSON.stringify(secret).includes('secret-value-123'))
  writeFileSync(join(root, 'feature/app.cjs'), 'exports.day = require("./other.cjs").parseDate\n')
  assert.equal(validateFacts(root, scoped, Date.now() + 5000), false)
  writeFileSync(join(root, 'feature/huge.cjs'), 'x'.repeat(256 * 1024 + 1))
  assert.equal(inspect({ paths: [], terms: ['parseDate'], searchPaths: ['feature/huge.cjs'] }).incomplete, true)
  assert.equal(inspect({ paths: [], terms: [], searchPaths: ['feature/app.cjs'] }).incomplete, true)
  assert.equal(inspectFacts(root, request, Date.now() - 1).incomplete, true)
  console.log('scoped facts: local search, exact lines, scope binding, overlap, paths, symlinks, secrets, changes and limits passed')
} finally { rmSync(root, { recursive: true, force: true }) }
