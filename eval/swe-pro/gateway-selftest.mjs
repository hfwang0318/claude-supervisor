import assert from 'node:assert/strict'
import { allowedRequest, actualModelAllowed, auditEvent } from './gateway.mjs'
assert.equal(allowedRequest('POST', '/v1/messages', { model: 'zhipu/glm-5.3[1m]', max_tokens: 2000 }), true)
assert.equal(allowedRequest('POST', '/v1/messages?beta=true', { model: 'zhipu/glm-5.3', max_tokens: 32000 }), true)
assert.equal(allowedRequest('POST', '/v1/messages?target=https://example.com', { model: 'zhipu/glm-5.3', max_tokens: 1 }), false)
for (const path of ['/v1/messages?target=https://example.com', '/v1/models', '/../../secret', 'https://example.com']) assert.equal(allowedRequest('POST', path, { model: 'zhipu/glm-5.3[1m]', max_tokens: 1 }), false)
for (const model of ['glm-5.2', 'opus', undefined]) assert.equal(allowedRequest('POST', '/v1/messages', { model, max_tokens: 1 }), false)
assert.equal(allowedRequest('GET', '/v1/messages', {}), false)
assert.equal(allowedRequest('POST', '/v1/messages', { model: 'zhipu/glm-5.3[1m]', max_tokens: 999999 }), false)
assert.equal(actualModelAllowed('glm-5.3'), true)
assert.equal(actualModelAllowed('glm-5.3-flash'), false)
const audit = auditEvent({ type: 'message_start', message: { model: 'glm-5.3', usage: { input_tokens: 15 }, content: [{ text: 'secret' }] } })
assert.equal(audit.model, 'glm-5.3')
assert.equal(audit.input, 15)
assert.equal(JSON.stringify(audit).includes('secret'), false)
assert.equal(auditEvent({ type: 'message', model: 'glm-5.3', usage: { input_tokens: 1, output_tokens: 2 } }).type, 'response')
console.log('SWE Pro gateway self-tests passed')
